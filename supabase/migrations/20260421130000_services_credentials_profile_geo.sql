-- 1) Helper: listable professional (SECURITY DEFINER + row_security off for RLS-safe checks)
create or replace function public.is_professional_publicly_listable(pro_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
set row_security = off
as $$
  select exists (
    select 1
    from public.users u
    inner join public.professional_search_profiles p on p.user_id = u.id
    where u.id = pro_id
      and coalesce(u.is_professional, false) = true
      and p.is_profile_complete = true
      and p.is_public_searchable = true
      and p.is_active = true
      and p.is_approved = true
  );
$$;

comment on function public.is_professional_publicly_listable(bigint) is
  'True when the professional appears in public search; used by RLS on services-related tables.';

revoke all on function public.is_professional_publicly_listable(bigint) from public;
grant execute on function public.is_professional_publicly_listable(bigint) to anon, authenticated;

