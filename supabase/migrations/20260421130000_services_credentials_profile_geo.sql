-- 4) services
create table public.services (
  id bigint generated by default as identity primary key,
  professional_id bigint not null references public.users (id) on delete cascade,
  specialty_id bigint references public.specialties (id) on delete set null,
  title text not null,
  description text,
  price_cents integer,
  currency_code text not null default 'GBP',
  duration_minutes integer,
  delivery_mode text not null,
  remote_scope text,
  provider_location_name text,
  service_area_type text,
  service_radius_km numeric(6, 2),
  service_area_text text,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint services_currency_code_len check (char_length(trim(currency_code)) = 3),
  constraint services_delivery_mode_check check (
    delivery_mode in ('remote', 'in_home', 'provider_location', 'hybrid')
  ),
  constraint services_remote_scope_check check (
    remote_scope is null
    or remote_scope in ('anywhere', 'country', 'region', 'custom')
  ),
  constraint services_service_area_type_check check (
    service_area_type is null
    or service_area_type in ('radius', 'place_list', 'custom_text')
  ),
  constraint services_price_cents_non_negative check (
    price_cents is null or price_cents >= 0
  ),
  constraint services_duration_non_negative check (
    duration_minutes is null or duration_minutes >= 0
  )
);

create index services_professional_id_idx on public.services (professional_id);
create index services_professional_active_idx on public.services (professional_id)
  where is_active = true;

create or replace function public.services_set_updated_at()
returns trigger
language plpgsql
as $fn$
begin
  new.updated_at := now();
  return new;
end;
$fn$;

drop trigger if exists services_set_updated_at on public.services;
create trigger services_set_updated_at
  before update on public.services
  for each row execute function public.services_set_updated_at();

alter table public.services enable row level security;

